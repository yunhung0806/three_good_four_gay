function arcCount(state,id){return Object.keys(ensureArc(state).arcFlags[id]||{}).length}
function arcLuck(state){const origins=new Set((state.links||[]).filter(link=>link?.from==='player'&&link.to!=='player'&&link.origin).map(link=>link.origin));return Math.min(.22,origins.size*.025)}
function arcStatus(state,id){ensureArc(state);const def=ARC_DEFINITIONS[id];if(!def)return 'none';const done=arcCount(state,id);if(done>=7)return 'complete';if(state.day<def.chapters[done].day)return 'locked';if(state.arcToday[id]===state.day)return 'done-today';return 'ready'}
